-- 06 LINK BETWEEN THE DESIGNED WAREHOUSE AND SNOWFLAKE
-- The designed warehouse (f1_warehouse.db) has these row counts; Snowflake must match.
-- Read-only.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE F1_WH;
USE DATABASE F1_PREDICTION_DB;

SELECT 'DW.FACT_RACE_RESULTS_STAR' AS snowflake_table, 8650 AS designed_rows, COUNT(*) AS snowflake_rows FROM DW.FACT_RACE_RESULTS_STAR
UNION ALL SELECT 'DW.DIM_DRIVER', 108, COUNT(*) FROM DW.DIM_DRIVER
UNION ALL SELECT 'DW.DIM_CONSTRUCTOR', 35, COUNT(*) FROM DW.DIM_CONSTRUCTOR
UNION ALL SELECT 'DW.DIM_RACE_STAR', 412, COUNT(*) FROM DW.DIM_RACE_STAR
UNION ALL SELECT 'DW.DIM_DATE', 412, COUNT(*) FROM DW.DIM_DATE
UNION ALL SELECT 'DW.FACT_RACE_RESULTS_SNOWFLAKE', 8650, COUNT(*) FROM DW.FACT_RACE_RESULTS_SNOWFLAKE
UNION ALL SELECT 'DW.DIM_RACE_SNOWFLAKE', 412, COUNT(*) FROM DW.DIM_RACE_SNOWFLAKE
UNION ALL SELECT 'DW.DIM_CIRCUIT', 38, COUNT(*) FROM DW.DIM_CIRCUIT
UNION ALL SELECT 'DW.DIM_COUNTRY', 30, COUNT(*) FROM DW.DIM_COUNTRY;
